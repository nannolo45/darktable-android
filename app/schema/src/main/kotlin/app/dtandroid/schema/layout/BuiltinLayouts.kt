package app.dtandroid.schema.layout

import app.dtandroid.schema.SchemaLoader.SchemaException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/**
 * darktable's built-in layouts at the pinned upstream commit, from
 * `schema/builtin-layouts.json` (generated by `tools/layouts/extract-builtin-layouts.py`).
 * darktable builds them anew at every start from its pixel workflow preference
 * (`plugins/darkroom/workflow`), so there is one set per workflow.
 */
class BuiltinLayouts(
    val darktableCommit: String,
    val opVersion: Int,
    val workflows: List<String>,
    val defaultWorkflow: String,
    /** the layout darktable falls back to: "workflow: scene-referred" */
    val fallbackLayout: String,
    /** darktable's default for the selected group (`plugins/darkroom/groups`): 0 active, 1.. the groups */
    val defaultGroup: Int,
    /** the "add widget" menu's recommended quick access entries (`RECOMMENDED_BASICS`) */
    val recommendedQuickAccess: List<String>,
    private val variants: Map<String, Variant>,
) {
    data class Preset(val name: String, val params: String)
    class Variant(val presets: List<Preset>, val newLayout: String)

    /** The built-in layouts for [workflow] in darktable's order of creation; unknown workflows get the default's. */
    fun presets(workflow: String): List<Preset> = variant(workflow).presets

    /** What "new" in "manage module layouts" starts from (`_presets_get_minimal`). */
    fun newLayout(workflow: String): String = variant(workflow).newLayout

    private fun variant(workflow: String) = variants[workflow] ?: variants.getValue(defaultWorkflow)

    companion object {
        const val RESOURCE = "dtandroid/schema/builtin-layouts.json"

        fun fromResources(loader: ClassLoader = BuiltinLayouts::class.java.classLoader): BuiltinLayouts =
            parse(loader.getResourceAsStream(RESOURCE)?.use { it.readBytes().decodeToString() }
                ?: throw SchemaException("builtin-layouts.json is not packed into the app"))

        fun parse(text: String): BuiltinLayouts {
            val o = Json.parseToJsonElement(text).jsonObject
            if (o["format"]?.jsonPrimitive?.int != 1) throw SchemaException("builtin-layouts.json: unsupported format")
            fun s(k: String) = o[k]?.jsonPrimitive?.content ?: throw SchemaException("builtin-layouts.json: no $k")
            val variants = (o["variants"] as? JsonObject ?: throw SchemaException("builtin-layouts.json: no variants")).mapValues { (_, v) ->
                val vo = v.jsonObject
                Variant(
                    vo["presets"]!!.jsonArray.map {
                        val p = it.jsonObject
                        require(p["writeprotect"]!!.jsonPrimitive.boolean) { "built-in layout not write-protected" }
                        Preset(p["name"]!!.jsonPrimitive.content, p["params"]!!.jsonPrimitive.content)
                    },
                    vo["new_layout"]!!.jsonPrimitive.content,
                )
            }
            val workflows = (o["workflows"] as JsonArray).map { it.jsonPrimitive.content }
            val default = s("default_workflow")
            if (default !in variants || workflows.any { it !in variants }) throw SchemaException("builtin-layouts.json: workflows incomplete")
            return BuiltinLayouts(
                darktableCommit = s("darktable_commit"),
                opVersion = o["op_version"]!!.jsonPrimitive.int,
                workflows = workflows,
                defaultWorkflow = default,
                fallbackLayout = s("fallback_layout"),
                defaultGroup = o["default_group"]!!.jsonPrimitive.int,
                recommendedQuickAccess = o["recommended_quick_access"]!!.jsonArray.map { it.jsonPrimitive.content },
                variants = variants,
            )
        }
    }
}
