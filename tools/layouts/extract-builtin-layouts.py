"""
Built-in module layouts (darktable's "module groups" presets) for the app (brief P2d).

    tools/layouts/extract-builtin-layouts.py <darktable source> [<output json>] [--check]

darktable builds its built-in layouts in `init_presets()` of src/libs/modulegroups.c
with a few macros (SQA, SNQA, SMG, AM) and two configuration lookups (the pixel
workflow). The "new" button of "manage module layouts" uses `_presets_get_minimal()`.
Nothing of this is typed by hand here: the script copies those functions and macros
verbatim out of the given source, compiles them with small stand-ins for the darktable
calls they make (string concatenation, configuration lookups, dt_lib_presets_add), runs
the result once per workflow listed in data/darktableconfig.xml.in and writes every
string exactly as darktable would store it in its presets table (C locale: the
translation macros return their English argument, as darktable does without a
translation).

It fails loudly when the source no longer has the expected shape: a function or macro
it copies is missing or appears twice, the copied code does not compile against the
stand-ins, it calls a configuration key or function the stand-ins do not know, or a
workflow produces no layout.

With --check the output file is not written; the script exits 1 if it differs from what
the source produces (CI uses this to show the data file matches the pinned upstream).

`tools/layouts/verify-with-darktable.sh` compares the result with what a real
darktable run stores in its database.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_OUT = os.path.join(REPO, "schema", "builtin-layouts.json")


class Fail(Exception):
    pass


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def one(pattern, text, what, flags=re.M | re.S):
    found = list(re.finditer(pattern, text, flags))
    if len(found) != 1:
        raise Fail(f"{what}: expected exactly one match, found {len(found)} (pattern {pattern!r})")
    return found[0]


def function(text, signature_regex, what):
    """The complete definition of a top-level C function: from its signature to the first '}' in column 0."""
    m = one(r"^" + signature_regex + r"\s*\n\{\n", text, what)
    end = text.find("\n}\n", m.end())
    if end < 0:
        raise Fail(f"{what}: no closing brace in column 0")
    return text[m.start():end + 3]


def macro(text, name, what):
    """A #define with its continuation lines."""
    m = one(r"^#define " + re.escape(name) + r"\b.*?(?<!\\)\n", text, what)
    return m.group(0)


def extract(src):
    mg_path = os.path.join(src, "src/libs/modulegroups.c")
    ut_path = os.path.join(src, "src/common/utility.c")
    cf_path = os.path.join(src, "data/darktableconfig.xml.in")
    mg, ut, cf = read(mg_path), read(ut_path), read(cf_path)

    parts = {
        "version": one(r"^DT_MODULE\((\d+)\)", mg, "DT_MODULE version").group(1),
        "macros": "".join(macro(mg, n, n) for n in (
            "FALLBACK_PRESET_NAME", "DEPRECATED_PRESET_NAME", "CURRENT_PRESET_NAME",
            "RECOMMENDED_BASICS", "SNQA", "SQA", "SMG", "AM")),
        "init_presets": function(mg, r"void init_presets\(dt_lib_module_t \*self\)", "init_presets"),
        "minimal": function(mg, r"static gchar \*_presets_get_minimal\(dt_lib_module_t \*self\)", "_presets_get_minimal"),
        "scene_referred": function(ut, r"gboolean dt_is_scene_referred\(void\)", "dt_is_scene_referred"),
    }

    # workflow options and default, and the default group, from the configuration schema
    root = ET.fromstring(re.sub(r"<!DOCTYPE[^>]*>", "", cf))
    def conf(name):
        hits = [e for e in root.iter("dtconfig") if (e.findtext("name") or "") == name]
        if len(hits) != 1:
            raise Fail(f"darktableconfig.xml.in: {name}: expected one entry, found {len(hits)}")
        return hits[0]
    wf = conf("plugins/darkroom/workflow")
    options = [o.text for o in wf.find("type").find("enum").findall("option")]
    default = wf.findtext("default")
    if not options or default not in options:
        raise Fail("darktableconfig.xml.in: workflow options or default not found")
    group_default = int(conf("plugins/darkroom/groups").findtext("default"))
    sources = {p: hashlib.sha256(open(os.path.join(src, p), "rb").read()).hexdigest()
               for p in ("src/libs/modulegroups.c", "src/common/utility.c", "data/darktableconfig.xml.in")}
    return parts, options, default, group_default, sources


HARNESS = r"""
/* generated by tools/layouts/extract-builtin-layouts.py: darktable code copied verbatim,
   with stand-ins for the calls it makes. Not part of the app. */
#include <glib.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define _(s) (s)
#define N_(s) (s)
#define C_(ctx, s) (s)

typedef struct dt_lib_module_t
{
  int pref_based_presets;
  const char *plugin_name;
  int (*version)(void);
} dt_lib_module_t;

static const char *g_workflow = NULL;
static int g_count = 0;

static void die(const char *what, const char *arg)
{
  fprintf(stderr, "harness: unexpected call %s(%s): the copied code needs a stand-in\n", what, arg ? arg : "");
  exit(3);
}

static gboolean dt_conf_is_equal(const char *key, const char *value)
{
  if(strcmp(key, "plugins/darkroom/workflow")) die("dt_conf_is_equal", key);
  return strcmp(g_workflow, value) == 0;
}

/* the key has a default in darktableconfig.xml, so it always exists: the
   "previous config" migration presets are never built */
static gboolean dt_conf_key_exists(const char *key)
{
  if(strcmp(key, "plugins/darkroom/modulegroups_preset")) die("dt_conf_key_exists", key);
  return TRUE;
}
static void dt_conf_set_string(const char *k, const char *v) { die("dt_conf_set_string", k); }
static gchar *_preset_retrieve_old_layout(const char *a, const char *b) { die("_preset_retrieve_old_layout", NULL); return NULL; }
static gchar *_preset_retrieve_old_layout_updated(void) { die("_preset_retrieve_old_layout_updated", NULL); return NULL; }
static void _preset_retrieve_old_presets(dt_lib_module_t *self) { }

static gchar *dt_util_str_cat(gchar **str, const gchar *format, ...)
{
  va_list ap;
  va_start(ap, format);
  gchar *add = g_strdup_vprintf(format, ap);
  va_end(ap);
  gchar *res = g_strconcat(*str ? *str : "", add, NULL);
  g_free(add);
  g_free(*str);
  *str = res;
  return res;
}

static void hex(const unsigned char *p, size_t n)
{
  for(size_t i = 0; i < n; i++) printf("%02x", p[i]);
}

static void dt_lib_presets_add(const char *name, const char *plugin_name, const int version,
                               const void *params, const int params_size, const gboolean readonly,
                               const int format)
{
  printf("{\"kind\":\"preset\",\"name_hex\":\"");
  hex((const unsigned char *)name, strlen(name));
  printf("\",\"operation\":\"%s\",\"op_version\":%d,\"writeprotect\":%d,\"format\":%d,\"params_hex\":\"",
         plugin_name, version, readonly ? 1 : 0, format);
  hex((const unsigned char *)params, params_size);
  printf("\"}\n");
  g_count++;
}

@SCENE_REFERRED@

@MACROS@

@INIT_PRESETS@

@MINIMAL@

static int _version(void) { return @VERSION@; }

int main(int argc, char **argv)
{
  if(argc != 2) return 2;
  g_workflow = argv[1];
  dt_lib_module_t self = { 0, "modulegroups", _version };
  init_presets(&self);
  if(g_count == 0) { fprintf(stderr, "harness: no preset built\n"); return 4; }
  gchar *minimal = _presets_get_minimal(&self);
  printf("{\"kind\":\"new_layout\",\"params_hex\":\"");
  hex((const unsigned char *)minimal, strlen(minimal));
  printf("\"}\n");
  printf("{\"kind\":\"constants\",\"fallback_hex\":\"");
  hex((const unsigned char *)FALLBACK_PRESET_NAME, strlen(FALLBACK_PRESET_NAME));
  printf("\",\"deprecated_hex\":\"");
  hex((const unsigned char *)DEPRECATED_PRESET_NAME, strlen(DEPRECATED_PRESET_NAME));
  printf("\",\"current_hex\":\"");
  hex((const unsigned char *)CURRENT_PRESET_NAME, strlen(CURRENT_PRESET_NAME));
  printf("\",\"recommended_hex\":\"");
  hex((const unsigned char *)RECOMMENDED_BASICS, strlen(RECOMMENDED_BASICS));
  printf("\"}\n");
  g_free(minimal);
  return 0;
}
"""


def build(parts, work):
    code = HARNESS
    for k, v in (("@SCENE_REFERRED@", parts["scene_referred"]), ("@MACROS@", parts["macros"]),
                 ("@INIT_PRESETS@", parts["init_presets"]), ("@MINIMAL@", parts["minimal"]),
                 ("@VERSION@", parts["version"])):
        code = code.replace(k, v)
    c = os.path.join(work, "harness.c")
    exe = os.path.join(work, "harness")
    with open(c, "w", encoding="utf-8") as f:
        f.write(code)
    flags = subprocess.run(["pkg-config", "--cflags", "--libs", "glib-2.0"], check=True,
                           capture_output=True, text=True).stdout.split()
    r = subprocess.run([os.environ.get("CC", "cc"), "-std=gnu11", "-O0", "-Wall", "-Wno-unused-function",
                        "-Wno-unused-variable", "-Wno-unused-but-set-variable", "-Werror=implicit-function-declaration",
                        "-o", exe, c] + flags, capture_output=True, text=True)
    if r.returncode != 0:
        raise Fail("the code copied from upstream does not compile against the stand-ins:\n" + r.stderr[-4000:])
    return exe


def run(exe, workflow):
    r = subprocess.run([exe, workflow], capture_output=True, text=True)
    if r.returncode != 0:
        raise Fail(f"harness failed for workflow {workflow!r} (exit {r.returncode}): {r.stderr.strip()}")
    presets, new_layout, consts = [], None, None
    for line in r.stdout.splitlines():
        o = json.loads(line)
        if o["kind"] == "preset":
            if o["operation"] != "modulegroups":
                raise Fail(f"preset for unexpected operation {o['operation']}")
            presets.append({
                "name": bytes.fromhex(o["name_hex"]).decode("utf-8"),
                "writeprotect": bool(o["writeprotect"]),
                "params": bytes.fromhex(o["params_hex"]).decode("utf-8"),
            })
            op_version = o["op_version"]
        elif o["kind"] == "new_layout":
            new_layout = bytes.fromhex(o["params_hex"]).decode("utf-8")
        else:
            consts = {k[:-4]: bytes.fromhex(v).decode("utf-8") for k, v in o.items() if k.endswith("_hex")}
    if not presets or new_layout is None or consts is None:
        raise Fail(f"workflow {workflow!r}: incomplete output")
    return presets, new_layout, consts, op_version


def git_commit(src):
    r = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"], capture_output=True, text=True)
    if r.returncode != 0:
        raise Fail(f"{src} is not a git checkout: the upstream commit must be recorded")
    return r.stdout.strip()


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    check = "--check" in argv
    if not args:
        print(__doc__)
        return 2
    src = os.path.abspath(args[0])
    out = os.path.abspath(args[1]) if len(args) > 1 else DEFAULT_OUT
    commit = git_commit(src)
    parts, options, default, group_default, sources = extract(src)
    variants = {}
    consts = None
    with tempfile.TemporaryDirectory() as work:
        exe = build(parts, work)
        for wf in options:
            presets, new_layout, consts, op_version = run(exe, wf)
            names = [p["name"] for p in presets]
            if len(set(names)) != len(names):
                raise Fail(f"workflow {wf!r}: duplicate preset names {names}")
            variants[wf] = {"presets": presets, "new_layout": new_layout}
    built = {p["name"] for v in variants.values() for p in v["presets"]}
    if consts["fallback"] not in built:
        raise Fail(f"fallback layout {consts['fallback']!r} is not among the built-in layouts")
    data = {
        "comment": "darktable's built-in module layouts (presets of the 'modulegroups' lib module), one set per "
                   "pixel workflow, as darktable stores them (C locale). Generated by "
                   "tools/layouts/extract-builtin-layouts.py; do not edit by hand.",
        "format": 1,
        "darktable_commit": commit,
        "sources_sha256": sources,
        "operation": "modulegroups",
        "op_version": int(parts["version"]),
        "workflow_conf": "plugins/darkroom/workflow",
        "workflows": options,
        "default_workflow": default,
        "fallback_layout": consts["fallback"],
        "deprecated_layout": consts["deprecated"],
        "deprecated_layout_built": consts["deprecated"] in built,
        "last_modified_layout": consts["current"],
        "default_group": group_default,
        "recommended_quick_access": [x for x in consts["recommended"].split("|") if x],
        "variants": variants,
    }
    text = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    if check:
        old = read(out) if os.path.exists(out) else ""
        if old != text:
            print(f"{out} differs from what {src} at {commit[:12]} produces", file=sys.stderr)
            return 1
        print(f"{out} matches {src} at {commit[:12]}")
        return 0
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    n = sum(len(v["presets"]) for v in variants.values())
    print(f"{out}: {len(variants)} workflows, {n} layouts, darktable {commit[:12]}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Fail as e:
        print(f"extract-builtin-layouts: {e}", file=sys.stderr)
        sys.exit(1)
