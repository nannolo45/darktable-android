"""Copy the private bauhaus widget structs out of darktable's bauhaus.c.

darktable keeps the layout of its slider/combobox/toggle widget in
src/bauhaus/bauhaus.c, not in a header. The extractor needs a few fields that
have no public getter (format, factor, offset, section, quad paint function,
combobox entry data). Instead of copying the struct by hand, this script copies
it verbatim from the exact source darktable was built from, at build time, so a
change upstream either changes the copy too or makes the build fail here.

Usage: gen_bauhaus_private.py <darktable source>/src/bauhaus/bauhaus.c <out.h>
"""
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
with open(src_path, encoding="utf-8") as f:
    text = f.read()

start_marker = "typedef struct dt_bauhaus_slider_data_t"
struct_marker = "struct _DtBauhausWidget\n{"
start = text.find(start_marker)
s = text.find(struct_marker)
if start < 0 or s < 0 or s < start:
    sys.exit("gen_bauhaus_private: bauhaus.c layout changed; markers not found")
end = text.find("\n};", s)
if end < 0:
    sys.exit("gen_bauhaus_private: end of struct _DtBauhausWidget not found")
body = text[start:end + 3]

# sanity: the fields the extractor reads must be present
for needed in ("const char *format;", "float factor;", "float offset;",
               "gchar *section;", "dt_bauhaus_quad_paint_f quad_paint;",
               "GPtrArray *entries;", "gpointer field;", "dt_bauhaus_type_t type;",
               "float (*curve)(float, dt_bauhaus_curve_t);", "gchar *tooltip;"):
    if needed not in body:
        sys.exit(f"gen_bauhaus_private: field '{needed}' not found in bauhaus.c")

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
    f.write("// GENERATED by gen_bauhaus_private.py from darktable's src/bauhaus/bauhaus.c.\n")
    f.write("// Do not edit. Private layout of the bauhaus widget, verbatim.\n")
    f.write("#pragma once\n#include \"bauhaus/bauhaus.h\"\n\n")
    f.write(body)
    f.write("\n")
